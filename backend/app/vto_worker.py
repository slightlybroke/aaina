"""Separate VTO worker: python -m app.vto_worker. Never auto-start on API requests."""

import asyncio
import logging
from datetime import datetime, timedelta
from uuid import uuid4

import httpx

from app.config import Settings
from app.domain import ContractError, ProviderError, transition, utcnow
from app.repository import Supabase
from app.vto_provider import VtoOptions, VtoProvider
from app.vto_repository import VtoRepository

log = logging.getLogger(__name__)


class VtoWorker:
    def __init__(self, repo, provider, settings):
        self.repo, self.provider, self.s = repo, provider, settings

    async def update(self, job, **values):
        if "status" in values:
            transition(job["status"], values["status"])
        values["updated_at"] = utcnow().isoformat()
        rows = await self.repo.patch(
            job["id"],
            values,
            lease_token=f"eq.{job['lease_token']}",
            status=f"eq.{job['status']}",
            lease_until=f"gt.{utcnow().isoformat()}",
        )
        if not rows:
            raise ProviderError("lease_lost")
        job.update(rows[0])

    async def fail(self, job, code):
        await self.update(
            job,
            status="failed",
            error_code=code,
            lease_token=None,
            lease_until=None,
            cleanup_next_at=utcnow().isoformat(),
        )

    async def process(self, job):
        if datetime.fromisoformat(job["expires_at"].replace("Z", "+00:00")) <= utcnow():
            await self.update(
                job, status="expired", error_code="job_expired", lease_token=None, lease_until=None
            )
            return
        if job["status"] == "submitting":
            await self.fail(job, "submission_unknown")
            return
        try:
            options = VtoOptions.model_validate(job["options"])
            if job["status"] == "pending":
                file_id = await self.provider.upload(await self.repo.download(job["source_path"]))
                await self.update(job, status="submitting")
                task = await self.provider.submit_vto(file_id, options)
                await self.update(
                    job,
                    status="processing",
                    external_task_id=task,
                    lease_token=None,
                    lease_until=None,
                    next_poll_at=(utcnow() + timedelta(seconds=self.s.poll_seconds)).isoformat(),
                )
                return
            state, url = await self.provider.status_vto(job["external_task_id"], options.mode)
            if state == "running":
                await self.update(
                    job,
                    lease_token=None,
                    lease_until=None,
                    next_poll_at=(utcnow() + timedelta(seconds=self.s.poll_seconds)).isoformat(),
                )
                return
            image = await self.provider.preview(url)
            # A repeated safe poll can recover an already-uploaded immutable preview.
            try:
                await self.repo.upload(job["result_path"], image)
            except httpx.HTTPStatusError as exc:
                if exc.response.status_code not in (400, 409):
                    raise
                # Accept a collision only when the server-generated bytes are identical.
                if await self.repo.download(job["result_path"]) != image:
                    raise ContractError("preview_conflict") from exc
            completed = await self.repo.rpc(
                "complete_vto_job", {"p_job": job["id"], "p_token": job["lease_token"]}
            )
            if not completed:
                await self.repo.patch(
                    job["id"],
                    {
                        "result_cleanup": "pending",
                        "cleanup_verified": False,
                        "cleanup_next_at": utcnow().isoformat(),
                    },
                )
        except (ContractError, ProviderError, httpx.HTTPError, ValueError) as exc:
            if getattr(exc, "code", "") == "lease_lost":
                return
            if job["status"] == "submitting":
                await self.fail(job, "submission_unknown")
                return
            attempts = job.get("attempts", 0) + 1
            if (
                isinstance(exc, httpx.HTTPError) or getattr(exc, "retryable", False)
            ) and attempts < 5:
                await self.update(
                    job,
                    attempts=attempts,
                    lease_token=None,
                    lease_until=None,
                    next_poll_at=(
                        utcnow() + timedelta(seconds=min(300, 10 * 2**attempts))
                    ).isoformat(),
                )
            else:
                code = (
                    str(exc)
                    if isinstance(exc, ContractError)
                    else getattr(exc, "code", "vto_failed")
                )
                await self.fail(job, code)

    async def cleanup(self):
        rows = await self.repo.rows(
            **{
                "cleanup_verified": "eq.false",
                "or": f"(expires_at.lte.{utcnow().isoformat()},status.in.(completed,failed,expired))",
                "cleanup_next_at": f"lte.{utcnow().isoformat()}",
                "order": "cleanup_next_at.asc",
                "limit": "20",
            }
        )
        for job in rows:
            expired = datetime.fromisoformat(job["expires_at"].replace("Z", "+00:00")) <= utcnow()
            terminal = job["status"] in {"completed", "failed", "expired"}
            final_sweep = (
                datetime.fromisoformat(job["expires_at"].replace("Z", "+00:00"))
                + timedelta(minutes=10)
                <= utcnow()
            )
            changes = {}
            failed = False
            for kind in ["source", "result"]:
                due = expired or (terminal and (kind == "source" or job["status"] != "completed"))
                if not due or (job[kind + "_cleanup"] == "deleted" and not final_sweep):
                    continue
                try:
                    await self.repo.delete(job[kind + "_path"])
                    changes[kind + "_cleanup"] = "deleted"
                except httpx.HTTPError:
                    failed = True
                    changes[kind + "_cleanup"] = "failed"
            next_cleanup = (
                (utcnow() + timedelta(minutes=5)).isoformat()
                if failed
                else (
                    (
                        datetime.fromisoformat(job["expires_at"].replace("Z", "+00:00"))
                        + timedelta(minutes=10 if expired else 0)
                    ).isoformat()
                )
            )
            changes.update(
                cleanup_attempts=job.get("cleanup_attempts", 0) + 1,
                cleanup_error="storage_delete_failed" if failed else None,
                cleanup_next_at=next_cleanup,
                cleanup_verified=final_sweep and not failed,
            )
            await self.repo.patch(job["id"], changes)
            if failed:
                log.warning("VTO cleanup failed; retry recorded")

    async def tick(self):
        await self.repo.rpc("expire_vto_jobs")
        await self.cleanup()
        jobs = await self.repo.rpc("claim_vto_job", {"p_token": str(uuid4())})
        if jobs:
            await self.process(jobs[0])
        return bool(jobs)


async def main():
    settings = Settings()
    if not settings.youcam_vto_enabled:
        raise SystemExit("Enable VTO only after its migration and provider setup.")
    async with httpx.AsyncClient(follow_redirects=False) as client:
        worker = VtoWorker(
            VtoRepository(Supabase(settings, client)), VtoProvider(settings, client), settings
        )
        while True:
            try:
                busy = await worker.tick()
            except Exception:
                log.error("VTO tick failed; durable job/cleanup state retained")
                busy = False
            await asyncio.sleep(1 if busy else 5)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    asyncio.run(main())
